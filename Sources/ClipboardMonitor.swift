import AppKit

/// Polls the general pasteboard (macOS has no change notification) and records new copies.
@MainActor
final class ClipboardMonitor {
    private let pb = NSPasteboard.general
    private let store: ClipStore
    private var lastChange: Int
    private var timer: Timer?

    var paused: Bool {
        get { UserDefaults.standard.bool(forKey: "paused") }
        set { UserDefaults.standard.set(newValue, forKey: "paused") }
    }

    /// Pasteboard types that password managers and other apps use to say "don't record this".
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    init(store: ClipStore) {
        self.store = store
        self.lastChange = NSPasteboard.general.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call after we write to the pasteboard ourselves so it isn't re-recorded.
    func markOwnWrite() { lastChange = pb.changeCount }

    private func check() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }

        let front = NSWorkspace.shared.frontmostApplication
        if front?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        let source = front?.localizedName

        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            store.add(ClipItem(kind: .files, files: urls.map(\.path), sourceApp: source))
        } else if let s = pb.string(forType: .string),
                  !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            store.add(ClipItem(kind: .text, text: s, sourceApp: source),
                      rich: RichData(rtf: pb.data(forType: .rtf), html: pb.data(forType: .html)))
        } else if let png = pngData() {
            store.addImage(png: png, source: source)
        }
    }

    private func pngData() -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
